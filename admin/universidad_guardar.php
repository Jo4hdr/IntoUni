<?php require_once __DIR__.'/../config/config.php';
require_role('admin');
if($_SERVER['REQUEST_METHOD']!=='POST')redirect('/admin/index.php');
verify_csrf();
$nombre=trim($_POST['nombre']??'');
$ciudad=trim($_POST['ciudad']??'');
$dep=trim($_POST['departamento']??'');
$email=filter_var(trim($_POST['email']??''),FILTER_VALIDATE_EMAIL);
$web=trim($_POST['sitio_web']??'');
$tipo=$_POST['tipo']==='publica'?'publica':'privada';
$pass=$_POST['password']??'';
if(!$nombre||!$ciudad||!$dep||!$email||strlen($pass)<8){flash('Completa todos los campos y usa una contraseña de al menos 8 caracteres.','error');
redirect('/admin/universidad_nueva.php');
}$hash=password_hash($pass,PASSWORD_DEFAULT);
try{$st=$db->prepare('INSERT INTO universidades(nombre,ciudad,departamento,tipo,sitio_web,email,password) VALUES(?,?,?,?,?,?,?)');
$st->bind_param('sssssss',$nombre,$ciudad,$dep,$tipo,$web,$email,$hash);
$st->execute();
flash('Universidad registrada correctamente.');
}catch(mysqli_sql_exception $e){flash('No se pudo registrar. Verifica que el correo no esté repetido.','error');
}redirect('/admin/index.php');
